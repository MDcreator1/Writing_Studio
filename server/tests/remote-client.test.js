function memoryStore() {
  const projects=new Map();
  return {
    async readRemoteProject(scope,id){return structuredClone(projects.get(JSON.stringify([scope,id]))||null);},
    async writeRemoteProject(state,expected){
      const key=JSON.stringify([state.scopeId,state.projectId]);
      if((projects.get(key)?.cacheVersion||0)!==expected){const error=Error('conflict');error.code='cache_conflict';throw error;}
      projects.set(key,structuredClone({...state,cacheVersion:expected+1}));return expected+1;
    }
  };
}

