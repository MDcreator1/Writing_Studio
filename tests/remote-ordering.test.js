'use strict';
const assert=require('node:assert/strict');
require('../assets/shared/js/06n-remote-workspace.js');
const {withOrder}=globalThis.LmRemoteWorkspace;
const previous=Array.from({length:10000},(_,i)=>({id:'p'+i,orderKey:(i+1)*1024}));
const inserted=withOrder([previous[0],{id:'new'},...previous.slice(1)],previous);
assert.ok(inserted[1].orderKey>previous[0].orderKey&&inserted[1].orderKey<previous[1].orderKey);
assert.equal(inserted.filter(item=>item.id!=='new'&&item.orderKey!==previous[Number(item.id.slice(1))].orderKey).length,0);
const moved=withOrder([previous.at(-1),...previous.slice(0,-1)],previous);
assert.ok(moved[0].orderKey<moved[1].orderKey);
assert.equal(moved.filter(item=>item.orderKey!==previous[Number(item.id.slice(1))].orderKey).length,1);
const dense=[{id:'a',orderKey:0},{id:'b',orderKey:1024}];
const front=withOrder([{id:'new'},...dense],dense);
assert.ok(front.every((item,index)=>item.orderKey>=0&&(!index||item.orderKey>front[index-1].orderKey)));
const narrow=[{id:'a',orderKey:1024},{id:'b',orderKey:1025},{id:'c',orderKey:2048}];
const repaired=withOrder([narrow[0],{id:'new'},...narrow.slice(1)],narrow);
assert.equal(repaired[0].orderKey,1024);assert.equal(repaired[3].orderKey,2048);
assert.ok(repaired[1].orderKey<repaired[2].orderKey);
console.log('remote ordering: 10k-paragraph insert/move and bounded gap repair passed');
